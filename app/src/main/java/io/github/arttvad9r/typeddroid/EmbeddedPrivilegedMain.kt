/**
 * TypedDroid-owned privileged helper bootstrapped by the embedded ADB client.
 *
 * Android SELinux does not allow an ordinary app domain to connect to a shell-owned Unix stream
 * socket. The helper therefore exposes a loopback-only TCP endpoint authenticated with a random
 * 256-bit secret generated by TypedDroid during bootstrap. Nothing is bound to a LAN interface.
 */
object EmbeddedPrivilegedMain {
    @JvmStatic
    fun main(args: Array<String>) {
        val config = parseArgs(args)
        check(Process.myUid() == Process.SHELL_UID) {
            "Embedded TypedDroid helper must run as Android shell UID."
        }

        ServerSocket().use { server ->
            server.reuseAddress = false
            server.bind(InetSocketAddress(InetAddress.getLoopbackAddress(), config.port), LISTEN_BACKLOG)
            while (true) {
                val client = server.accept()
                val shouldExit = try {
                    client.soTimeout = CLIENT_READ_TIMEOUT_MILLIS
                    client.tcpNoDelay = true
                    handleClient(client, config.authToken)
                } finally {
                    runCatching { client.close() }
                }
                if (shouldExit) break
            }
        }
        exitProcess(0)
    }

    private fun handleClient(socket: Socket, expectedAuthToken: String): Boolean {
        val request = runCatching {
            EmbeddedPrivilegedProtocol.readRequest(socket.getInputStream())
        }.getOrElse { error ->
            runCatching {
                EmbeddedPrivilegedProtocol.writeResponse(
                    socket.getOutputStream(),
                    EmbeddedPrivilegedResponse(
                        id = "invalid",
                        ok = false,
                        error = safeError(error),
                    ),
                )
            }
            return false
        }

        if (!constantTimeTokenEquals(request.authToken, expectedAuthToken)) {
            EmbeddedPrivilegedProtocol.writeResponse(
                socket.getOutputStream(),
                EmbeddedPrivilegedResponse(
                    id = request.id,
                    ok = false,
                    error = "Embedded privileged authentication failed.",
                ),
            )
            return false
        }

        if (request.operation == EmbeddedPrivilegedProtocol.OP_READ_FILE_STREAM) {
            streamFileToClient(request, socket.getOutputStream())
            return false
        }

        val response = when (request.operation) {
            EmbeddedPrivilegedProtocol.OP_PING -> EmbeddedPrivilegedResponse(
                id = request.id,
                ok = true,
            )

            EmbeddedPrivilegedProtocol.OP_EXEC -> execute(request)
            EmbeddedPrivilegedProtocol.OP_INSTALL_APK -> installApk(request, socket.getInputStream())
            EmbeddedPrivilegedProtocol.OP_UNINSTALL_APP -> uninstallApp(request)
            EmbeddedPrivilegedProtocol.OP_FORCE_STOP_APP -> forceStopApp(request)
            EmbeddedPrivilegedProtocol.OP_REVOKE_PERMISSION -> revokePermission(request)
            EmbeddedPrivilegedProtocol.OP_BATTERY_STATS -> batteryStats(request)
            EmbeddedPrivilegedProtocol.OP_UI_HIERARCHY -> uiHierarchy(request)
            EmbeddedPrivilegedProtocol.OP_UI_SCREENSHOT -> uiScreenshot(request)
            EmbeddedPrivilegedProtocol.OP_UI_TAP -> uiTap(request)
            EmbeddedPrivilegedProtocol.OP_UI_SWIPE -> uiSwipe(request)
            EmbeddedPrivilegedProtocol.OP_UI_TEXT -> uiText(request)
            EmbeddedPrivilegedProtocol.OP_UI_KEY -> uiKey(request)
            EmbeddedPrivilegedProtocol.OP_OPEN_APP -> openApp(request)
            EmbeddedPrivilegedProtocol.OP_WRITE_FILE_STREAM -> writeFileFromClient(request, socket.getInputStream())

            EmbeddedPrivilegedProtocol.OP_SHUTDOWN -> EmbeddedPrivilegedResponse(
                id = request.id,
                ok = true,
            )

            else -> EmbeddedPrivilegedResponse(
                id = request.id,
                ok = false,
                error = "Unknown privileged operation.",
            )
        }
        EmbeddedPrivilegedProtocol.writeResponse(socket.getOutputStream(), response)
        return request.operation == EmbeddedPrivilegedProtocol.OP_SHUTDOWN && response.ok
    }

    private fun constantTimeTokenEquals(actual: String, expected: String): Boolean =
        MessageDigest.isEqual(actual.encodeToByteArray(), expected.encodeToByteArray())

    private fun execute(request: EmbeddedPrivilegedRequest): EmbeddedPrivilegedResponse {
        val command = request.command
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Shell command is missing.")
        if (command.isEmpty() || command.encodeToByteArray().size > EmbeddedPrivilegedProtocol.MAX_COMMAND_BYTES || '\u0000' in command) {
            return EmbeddedPrivilegedResponse(request.id, false, error = "Shell command is invalid.")
        }
        val timeout = request.timeoutMillis ?: DEFAULT_TIMEOUT_MILLIS
        if (timeout !in 1..EmbeddedPrivilegedProtocol.MAX_TIMEOUT_MILLIS) {
            return EmbeddedPrivilegedResponse(request.id, false, error = "Shell timeout is invalid.")
        }
        return executeProcess(
            requestId = request.id,
            argv = arrayOf("/system/bin/sh", "-c", command),
            timeoutMillis = timeout,
            stdoutLimit = MAX_RETAINED_STREAM_BYTES,
            stderrLimit = MAX_RETAINED_STREAM_BYTES,
        )
    }

    private fun installApk(
        request: EmbeddedPrivilegedRequest,
        input: java.io.InputStream,
    ): EmbeddedPrivilegedResponse {
        val size = request.artifactSizeBytes
            ?.takeIf { it in 1..MAX_APK_ARTIFACT_BYTES }
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "APK size is invalid.")
        val expectedSha = request.artifactSha256
            ?.takeIf { SHA256_REGEX.matches(it) }
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "APK SHA-256 is invalid.")
        val replace = request.replace ?: true
        val staged = File("/data/local/tmp/typed-droid-${UUID.randomUUID()}.apk")
        return try {
            val digest = MessageDigest.getInstance("SHA-256")
            var remaining = size
            FileOutputStream(staged).buffered().use { output ->
                val buffer = ByteArray(64 * 1024)
                while (remaining > 0) {
                    val read = input.read(buffer, 0, minOf(buffer.size.toLong(), remaining).toInt())
                    if (read < 0) error("APK stream ended before the declared size.")
                    if (read == 0) continue
                    digest.update(buffer, 0, read)
                    output.write(buffer, 0, read)
                    remaining -= read
                }
            }
            check(staged.length() == size) { "Staged APK size mismatch." }
            check(digest.digest().toHex() == expectedSha) { "Staged APK SHA-256 mismatch." }
            executeProcess(
                requestId = request.id,
                argv = buildPmInstallCommand(staged.absolutePath, replace),
                timeoutMillis = APK_INSTALL_TIMEOUT_MILLIS,
                stdoutLimit = TYPED_COMMAND_OUTPUT_BYTES,
                stderrLimit = TYPED_COMMAND_OUTPUT_BYTES,
            )
        } catch (error: Throwable) {
            EmbeddedPrivilegedResponse(request.id, false, error = safeError(error))
        } finally {
            runCatching { staged.delete() }
        }
    }


    private fun streamFileToClient(request: EmbeddedPrivilegedRequest, output: java.io.OutputStream) {
        val path = normalizedTransferPath(request.filePath, mutation = false)
        if (path == null) {
            EmbeddedPrivilegedProtocol.writeResponse(output, EmbeddedPrivilegedResponse(request.id, false, error = "File path is invalid."))
            return
        }
        val file = File(path)
        if (!file.isFile) {
            EmbeddedPrivilegedProtocol.writeResponse(output, EmbeddedPrivilegedResponse(request.id, false, error = "File is not a readable regular file."))
            return
        }
        val size = file.length()
        if (size !in 1..EmbeddedPrivilegedProtocol.MAX_TRANSFER_FILE_BYTES) {
            EmbeddedPrivilegedProtocol.writeResponse(output, EmbeddedPrivilegedResponse(request.id, false, error = "File size is outside the transfer limit."))
            return
        }
        EmbeddedPrivilegedProtocol.writeResponse(
            output,
            EmbeddedPrivilegedResponse(id = request.id, ok = true, exitCode = 0, sizeBytes = size),
        )
        file.inputStream().buffered().use { input ->
            val buffer = ByteArray(64 * 1024)
            var remaining = size
            while (remaining > 0) {
                val read = input.read(buffer, 0, minOf(buffer.size.toLong(), remaining).toInt())
                check(read >= 0) { "File changed while it was being streamed." }
                if (read == 0) continue
                output.write(buffer, 0, read)
                remaining -= read
            }
            output.flush()
        }
    }

    private fun writeFileFromClient(
        request: EmbeddedPrivilegedRequest,
        input: java.io.InputStream,
    ): EmbeddedPrivilegedResponse {
        val path = normalizedTransferPath(request.filePath, mutation = true)
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Destination path is invalid or outside trusted writable roots.")
        val size = request.fileSizeBytes
            ?.takeIf { it in 1..EmbeddedPrivilegedProtocol.MAX_TRANSFER_FILE_BYTES }
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Transfer size is invalid.")
        val expectedSha = request.fileSha256
            ?.takeIf { SHA256_REGEX.matches(it) }
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Transfer SHA-256 is invalid.")
        val overwrite = request.overwrite ?: false
        val createParents = request.createParents ?: true
        val target = File(path)
        if (target.exists() && !overwrite) {
            return EmbeddedPrivilegedResponse(request.id, false, error = "Destination already exists and overwrite is disabled.")
        }
        val parent = target.parentFile
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Destination parent is invalid.")
        val temp = File(parent, ".typeddroid-transfer-${UUID.randomUUID()}.part")
        return try {
            if (!parent.exists() && createParents && !parent.mkdirs()) {
                error("Destination parent directories could not be created.")
            }
            check(parent.isDirectory) { "Destination parent is not a directory." }
            val digest = MessageDigest.getInstance("SHA-256")
            var remaining = size
            FileOutputStream(temp).buffered().use { fileOutput ->
                val buffer = ByteArray(64 * 1024)
                while (remaining > 0) {
                    val read = input.read(buffer, 0, minOf(buffer.size.toLong(), remaining).toInt())
                    if (read < 0) error("Transfer stream ended before the declared size.")
                    if (read == 0) continue
                    digest.update(buffer, 0, read)
                    fileOutput.write(buffer, 0, read)
                    remaining -= read
                }
            }
            check(temp.length() == size) { "Transferred file size mismatch." }
            check(digest.digest().toHex() == expectedSha) { "Transferred file SHA-256 mismatch." }
            val sourcePath = temp.toPath()
            val targetPath = target.toPath()
            try {
                if (overwrite) {
                    Files.move(sourcePath, targetPath, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING)
                } else {
                    Files.move(sourcePath, targetPath, StandardCopyOption.ATOMIC_MOVE)
                }
            } catch (_: Exception) {
                if (overwrite) Files.move(sourcePath, targetPath, StandardCopyOption.REPLACE_EXISTING)
                else Files.move(sourcePath, targetPath)
            }
            EmbeddedPrivilegedResponse(id = request.id, ok = true, exitCode = 0, sizeBytes = size, sha256 = expectedSha)
        } catch (error: Throwable) {
            EmbeddedPrivilegedResponse(request.id, false, error = safeError(error))
        } finally {
            runCatching { temp.delete() }
        }
    }

    private fun normalizedTransferPath(raw: String?, mutation: Boolean): String? {
        val value = raw ?: return null
        if (!value.startsWith('/') || '\u0000' in value || '\n' in value || '\r' in value ||
            value.encodeToByteArray().size > EmbeddedPrivilegedProtocol.MAX_TRANSFER_PATH_BYTES) return null
        val normalized = runCatching { Paths.get(value).normalize().toString() }.getOrNull() ?: return null
        if (!normalized.startsWith('/')) return null
        if (mutation) {
            if (TRUSTED_TRANSFER_WRITE_ROOTS.none { normalized.startsWith("$it/") }) return null
        }
        return normalized
    }

    private fun uninstallApp(request: EmbeddedPrivilegedRequest): EmbeddedPrivilegedResponse {
        val packageName = request.packageName
            ?.takeIf(::isValidAndroidQualifiedName)
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Package name is invalid.")
        return executeProcess(
            request.id,
            buildPmUninstallCommand(packageName, request.keepData ?: false),
            TYPED_COMMAND_TIMEOUT_MILLIS,
            TYPED_COMMAND_OUTPUT_BYTES,
            TYPED_COMMAND_OUTPUT_BYTES,
        )
    }

    private fun forceStopApp(request: EmbeddedPrivilegedRequest): EmbeddedPrivilegedResponse {
        val packageName = request.packageName
            ?.takeIf(::isValidAndroidQualifiedName)
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Package name is invalid.")
        return executeProcess(
            request.id,
            buildAmForceStopCommand(packageName),
            TYPED_COMMAND_TIMEOUT_MILLIS,
            TYPED_COMMAND_OUTPUT_BYTES,
            TYPED_COMMAND_OUTPUT_BYTES,
        )
    }

    private fun revokePermission(request: EmbeddedPrivilegedRequest): EmbeddedPrivilegedResponse {
        val packageName = request.packageName
            ?.takeIf(::isValidAndroidQualifiedName)
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Package name is invalid.")
        val permissionName = request.permissionName
            ?.takeIf(::isValidAndroidQualifiedName)
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Permission name is invalid.")
        val userId = request.userId
            ?.takeIf(::isSupportedAndroidUserId)
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Android user ID is invalid.")
        return executeProcess(
            request.id,
            buildPmRevokePermissionCommand(packageName, permissionName, userId),
            TYPED_COMMAND_TIMEOUT_MILLIS,
            TYPED_COMMAND_OUTPUT_BYTES,
            TYPED_COMMAND_OUTPUT_BYTES,
        )
    }

    private fun batteryStats(request: EmbeddedPrivilegedRequest): EmbeddedPrivilegedResponse =
        executeProcess(
            request.id,
            buildBatteryStatsCommand(),
            BATTERY_STATS_TIMEOUT_MILLIS,
            MAX_BATTERY_STATS_OUTPUT_BYTES,
            TYPED_COMMAND_OUTPUT_BYTES,
        )

    private fun uiHierarchy(request: EmbeddedPrivilegedRequest): EmbeddedPrivilegedResponse {
        val target = File("/data/local/tmp/typed-droid-ui-${UUID.randomUUID()}.xml")
        return try {
            val dump = executeProcess(
                request.id,
                arrayOf("/system/bin/uiautomator", "dump", target.absolutePath),
                UI_COMMAND_TIMEOUT_MILLIS,
                TYPED_COMMAND_OUTPUT_BYTES,
                TYPED_COMMAND_OUTPUT_BYTES,
            )
            if (!dump.ok || dump.exitCode != 0) return dump
            val captured = target.inputStream().use { readBounded(it, MAX_UI_HIERARCHY_BYTES) }
            EmbeddedPrivilegedResponse(
                id = request.id,
                ok = true,
                exitCode = 0,
                stdoutBase64 = Base64.getEncoder().encodeToString(captured.bytes),
                stdoutTruncated = captured.truncated,
            )
        } catch (error: Throwable) {
            EmbeddedPrivilegedResponse(request.id, false, error = safeError(error))
        } finally {
            runCatching { target.delete() }
        }
    }

    private fun uiTap(request: EmbeddedPrivilegedRequest): EmbeddedPrivilegedResponse {
        val x = request.x?.takeIf(::isValidUiCoordinate)
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Invalid tap x coordinate.")
        val y = request.y?.takeIf(::isValidUiCoordinate)
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Invalid tap y coordinate.")
        return executeProcess(request.id, arrayOf("/system/bin/input", "tap", x.toString(), y.toString()), UI_COMMAND_TIMEOUT_MILLIS, TYPED_COMMAND_OUTPUT_BYTES, TYPED_COMMAND_OUTPUT_BYTES)
    }

    private fun uiSwipe(request: EmbeddedPrivilegedRequest): EmbeddedPrivilegedResponse {
        val values = listOf(request.startX, request.startY, request.endX, request.endY)
        if (values.any { it == null || !isValidUiCoordinate(it) }) {
            return EmbeddedPrivilegedResponse(request.id, false, error = "Invalid swipe coordinates.")
        }
        val duration = request.durationMillis?.takeIf { it in 1..MAX_UI_SWIPE_DURATION_MILLIS }
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Invalid swipe duration.")
        return executeProcess(
            request.id,
            arrayOf("/system/bin/input", "swipe", request.startX.toString(), request.startY.toString(), request.endX.toString(), request.endY.toString(), duration.toString()),
            UI_COMMAND_TIMEOUT_MILLIS, TYPED_COMMAND_OUTPUT_BYTES, TYPED_COMMAND_OUTPUT_BYTES,
        )
    }

    private fun uiText(request: EmbeddedPrivilegedRequest): EmbeddedPrivilegedResponse {
        val text = request.text?.takeIf { value ->
            value.isNotEmpty() && value.encodeToByteArray().size <= MAX_UI_TEXT_BYTES && '\u0000' !in value
        } ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Invalid UI text.")
        return executeProcess(request.id, arrayOf("/system/bin/input", "text", text), UI_COMMAND_TIMEOUT_MILLIS, TYPED_COMMAND_OUTPUT_BYTES, TYPED_COMMAND_OUTPUT_BYTES)
    }

    private fun uiKey(request: EmbeddedPrivilegedRequest): EmbeddedPrivilegedResponse {
        val keyCode = request.keyCode?.takeIf { it in 0..MAX_UI_KEY_CODE }
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Invalid key code.")
        return executeProcess(request.id, arrayOf("/system/bin/input", "keyevent", keyCode.toString()), UI_COMMAND_TIMEOUT_MILLIS, TYPED_COMMAND_OUTPUT_BYTES, TYPED_COMMAND_OUTPUT_BYTES)
    }

    private fun openApp(request: EmbeddedPrivilegedRequest): EmbeddedPrivilegedResponse {
        val packageName = request.packageName?.takeIf(::isValidAndroidQualifiedName)
            ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Package name is invalid.")
        return executeProcess(
            request.id,
            arrayOf("/system/bin/monkey", "-p", packageName, "-c", "android.intent.category.LAUNCHER", "1"),
            UI_COMMAND_TIMEOUT_MILLIS, TYPED_COMMAND_OUTPUT_BYTES, TYPED_COMMAND_OUTPUT_BYTES,
        )
    }

    private fun uiScreenshot(request: EmbeddedPrivilegedRequest): EmbeddedPrivilegedResponse {
        val target = File("/data/local/tmp/typed-droid-screen-${UUID.randomUUID()}.png")
        return try {
            val capture = executeProcess(
                request.id,
                arrayOf("/system/bin/screencap", "-p", target.absolutePath),
                UI_COMMAND_TIMEOUT_MILLIS, TYPED_COMMAND_OUTPUT_BYTES, TYPED_COMMAND_OUTPUT_BYTES,
            )
            if (!capture.ok) return capture
            if (capture.exitCode != 0) {
                return EmbeddedPrivilegedResponse(
                    id = request.id,
                    ok = false,
                    error = "Android screenshot command failed.",
                )
            }
            val source = BitmapFactory.decodeFile(target.absolutePath)
                ?: return EmbeddedPrivilegedResponse(request.id, false, error = "Android screenshot could not be decoded.")
            try {
                val encoded = encodeBoundedScreenshot(source)
                EmbeddedPrivilegedResponse(
                    id = request.id,
                    ok = true,
                    exitCode = 0,
                    stdoutBase64 = Base64.getEncoder().encodeToString(encoded.bytes),
                    imageWidth = encoded.width,
                    imageHeight = encoded.height,
                    mimeType = "image/jpeg",
                )
            } finally {
                source.recycle()
            }
        } catch (error: Throwable) {
            EmbeddedPrivilegedResponse(request.id, false, error = safeError(error))
        } finally {
            runCatching { target.delete() }
        }
    }

    private fun encodeBoundedScreenshot(source: Bitmap): EncodedScreenshot {
        for (maxDimension in intArrayOf(960, 800, 640, 512)) {
            val scale = minOf(1.0, maxDimension.toDouble() / maxOf(source.width, source.height).toDouble())
            val width = maxOf(1, (source.width * scale).toInt())
            val height = maxOf(1, (source.height * scale).toInt())
            val bitmap = if (width == source.width && height == source.height) source else
                Bitmap.createScaledBitmap(source, width, height, true)
            try {
                for (quality in intArrayOf(80, 70, 60, 50, 40, 30)) {
                    val output = ByteArrayOutputStream(MAX_UI_SCREENSHOT_BYTES)
                    check(bitmap.compress(Bitmap.CompressFormat.JPEG, quality, output)) { "JPEG compression failed." }
                    val bytes = output.toByteArray()
                    if (bytes.size <= MAX_UI_SCREENSHOT_BYTES) return EncodedScreenshot(bytes, width, height)
                }
            } finally {
                if (bitmap !== source) bitmap.recycle()
            }
        }
        error("Screenshot could not be compressed below the remote safety limit.")
    }

    private data class EncodedScreenshot(val bytes: ByteArray, val width: Int, val height: Int)

    private fun isValidUiCoordinate(value: Int): Boolean = value in 0..MAX_UI_COORDINATE

    private fun executeProcess(
        requestId: String,
        argv: Array<String>,
        timeoutMillis: Long,
        stdoutLimit: Int,
        stderrLimit: Int,
    ): EmbeddedPrivilegedResponse {
        val process = try {
            ProcessBuilder(*argv).start()
        } catch (error: Throwable) {
            return EmbeddedPrivilegedResponse(requestId, false, error = safeError(error))
        }
        runCatching { process.outputStream.close() }
        val executor = Executors.newFixedThreadPool(2)
        return try {
            val stdoutFuture = executor.submit<CapturedOutput> { process.inputStream.use { readBounded(it, stdoutLimit) } }
            val stderrFuture = executor.submit<CapturedOutput> { process.errorStream.use { readBounded(it, stderrLimit) } }
            val finished = process.waitFor(timeoutMillis, TimeUnit.MILLISECONDS)
            if (!finished) {
                process.destroyForcibly()
                stdoutFuture.cancel(true)
                stderrFuture.cancel(true)
                EmbeddedPrivilegedResponse(
                    id = requestId,
                    ok = false,
                    timedOut = true,
                    error = "Privileged command timed out.",
                )
            } else {
                val stdout = stdoutFuture.get()
                val stderr = stderrFuture.get()
                EmbeddedPrivilegedResponse(
                    id = requestId,
                    ok = true,
                    exitCode = process.exitValue(),
                    stdoutBase64 = Base64.getEncoder().encodeToString(stdout.bytes),
                    stderrBase64 = Base64.getEncoder().encodeToString(stderr.bytes),
                    stdoutTruncated = stdout.truncated,
                    stderrTruncated = stderr.truncated,
                )
            }
        } catch (error: Throwable) {
            runCatching { process.destroyForcibly() }
            EmbeddedPrivilegedResponse(requestId, false, error = safeError(error))
        } finally {
            executor.shutdownNow()
        }
    }

    private fun readBounded(input: java.io.InputStream, limitBytes: Int): CapturedOutput {
        require(limitBytes > 0)
        val output = ByteArrayOutputStream(minOf(limitBytes, 64 * 1024))
        val buffer = ByteArray(16 * 1024)
        var retained = 0
        var truncated = false
        while (true) {
            val count = input.read(buffer)
            if (count < 0) break
            val keep = minOf(count, limitBytes - retained)
            if (keep > 0) {
                output.write(buffer, 0, keep)
                retained += keep
            }
            if (keep < count) truncated = true
        }
        return CapturedOutput(output.toByteArray(), truncated)
    }

    private data class CapturedOutput(
        val bytes: ByteArray,
        val truncated: Boolean,
    )

    private fun parseArgs(args: Array<String>): Config {
        require(args.size == 4 && args[0] == "--port" && args[2] == "--token") {
            "Invalid TypedDroid privileged helper arguments."
        }
        val port = args[1].toIntOrNull()
            ?.takeIf { it in 1..65535 }
            ?: throw IllegalArgumentException("Invalid privileged loopback port.")
        val authToken = args[3]
        require(isValidEmbeddedPrivilegedAuthToken(authToken)) { "Invalid privileged auth token." }
        return Config(port, authToken)
    }

    private fun safeError(error: Throwable): String =
        ((error.cause ?: error).message ?: error::class.java.simpleName).take(300)

    private data class Config(val port: Int, val authToken: String)

    private const val DEFAULT_TIMEOUT_MILLIS = 30_000L
    private const val LISTEN_BACKLOG = 8
    private const val CLIENT_READ_TIMEOUT_MILLIS = 5_000
    // Raw-shell stdout/stderr remain bounded well below the privileged RPC frame limit.
    private const val MAX_RETAINED_STREAM_BYTES = 384 * 1024
    private const val TYPED_COMMAND_OUTPUT_BYTES = 64 * 1024
    private const val TYPED_COMMAND_TIMEOUT_MILLIS = 30_000L
    private const val APK_INSTALL_TIMEOUT_MILLIS = 5 * 60 * 1000L
    private const val BATTERY_STATS_TIMEOUT_MILLIS = 30_000L
    private const val UI_COMMAND_TIMEOUT_MILLIS = 10_000L
    private const val MAX_UI_HIERARCHY_BYTES = 96 * 1024
    private const val MAX_UI_SCREENSHOT_BYTES = 128 * 1024
    private const val MAX_UI_TEXT_BYTES = 2 * 1024
    private const val MAX_UI_COORDINATE = 32_767
    private const val MAX_UI_SWIPE_DURATION_MILLIS = 10_000
    private const val MAX_UI_KEY_CODE = 1_000
    private val SHA256_REGEX = Regex("^[0-9a-f]{64}$")
    private val TRUSTED_TRANSFER_WRITE_ROOTS = listOf("/sdcard", "/storage/emulated/0", "/data/local/tmp")
    private fun ByteArray.toHex(): String = joinToString("") { "%02x".format(it) }

}
